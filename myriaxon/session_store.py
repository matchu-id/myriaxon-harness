import json
import os
import time
import uuid
from dataclasses import dataclass
from pathlib import Path

from .atomic_io import atomic_write_text
from .constants import PROJECT_SESSION_DIR, SESSION_FILENAME


# Branches live beside the main session rather than replacing it.
#
# The first version of `fork_session` wrote every branch to `session.json`, which meant creating a branch DESTROYED
# the conversation it branched from -- the exact opposite of the feature's purpose, and invisible until the parent
# was read back. A branch needs its own file. Kept in a subdirectory so `.myriaxon/` does not fill with an
# unbounded number of sibling JSON files as branches accumulate.
BRANCH_DIR = "branches"


def _session_path(project_root: Path | None = None, session_id: str = "") -> Path:
    root = project_root if project_root is not None else Path.cwd()
    base = root / PROJECT_SESSION_DIR
    if not session_id:
        return base / SESSION_FILENAME
    # The id is generated by `new_session_id` (hex plus a timestamp) but it arrives from a file the user can edit,
    # so it is sanitised rather than trusted: a path separator here would let a crafted id write outside the
    # project directory.
    safe = "".join(ch for ch in session_id if ch.isalnum() or ch in "-_")
    if not safe:
        return base / SESSION_FILENAME
    return base / BRANCH_DIR / f"{safe}.json"


def list_branches(project_root: Path | None = None) -> list[str]:
    """Session ids that have their own file, sorted. Used by the tree listing to find orphans."""
    root = project_root if project_root is not None else Path.cwd()
    directory = root / PROJECT_SESSION_DIR / BRANCH_DIR
    if not directory.is_dir():
        return []
    return sorted(p.stem for p in directory.glob("*.json"))


# ---------------------------------------------------------------------------------------
# The writer claim
# ---------------------------------------------------------------------------------------
#
# `save_session` used to be a pure last-write-wins overwrite, which is wrong the moment two Myriaxon processes
# share a project directory -- two terminals, a dashboard turn and a terminal turn, a Locus waking while the user
# is typing. The second writer silently replaces the first one's transcript, and the first one never learns it.
# The losing side of that race is unbounded: it is however many turns the other process had accumulated.
#
# This is the same defect OpenClaw fences with `activeWriterRunId` / `expectedWriterRunId`, verified in
# `src/config/sessions/session-accessor.sqlite-scope.ts`. Their formulation is a durable per-session claim that
# every transcript mutation must re-supply, checked inside the same transaction as the write. The shape below is
# the same idea reduced to what a JSON session file can support: the claim travels in the file, and a write is
# only accepted if the claim on disk still matches the one this writer loaded.
#
# What it does not claim: this is not a lock and does not serialize writers. Two processes may both be running
# turns; the fence only guarantees that a writer whose view of the session is no longer current cannot destroy
# the transcript that superseded it. Whoever saved first keeps their work; the stale writer is told it was
# fenced so it can start from current state instead of silently losing it.
SESSION_CLAIM_FIELD = "writer_claim"


def new_writer_id() -> str:
    """A unique id for one process's claim on a session.

    Process id plus a random suffix rather than the pid alone: pids are reused, and two claims from recycled
    pids would compare equal and defeat the fence entirely.
    """
    return f"{os.getpid()}-{uuid.uuid4().hex[:8]}"


@dataclass
class SaveOutcome:
    """What happened to a save attempt."""

    written: bool
    fenced: bool = False
    reason: str = ""

    def __bool__(self) -> bool:
        return self.written


def save_session(
    provider: str,
    model: str,
    mode: str,
    effort: str | None,
    thinking: bool,
    messages: list[dict],
    project_root: Path | None = None,
    *,
    writer_id: str = "",
    strict: bool = False,
    session_id: str = "",
    as_branch: bool = False,
) -> SaveOutcome:
    """Persist the session, refusing to overwrite a transcript another writer has claimed since.

    `writer_id` identifies this process's claim. When it is empty the write is unconditional, preserving the
    behaviour of every existing caller that has not opted in -- the fence is only meaningful for a caller that
    keeps a stable id across turns, and silently fencing a caller that passes nothing would break sessions
    rather than protect them.

    `strict=True` re-reads the file immediately before writing and fails if the claim changed, which narrows the
    race to the window between that read and the rename. That window cannot be closed with a JSON file: a real
    fix needs the compare-and-set to happen inside the same transaction as the write, which is what OpenClaw
    gets from SQLite. `strict=False` trusts the claim captured at load time, which catches the common case (a
    long-lived process whose counterpart saved minutes ago) without a second read on every turn.
    """
    # The path is chosen by WHERE the write belongs, not by whether an id was supplied. Conflating the two was the
    # second version's bug: passing an identity sent the write to `branches/`, so the main session file was never
    # created and every fork then failed to find a parent. A name identifies a session; `as_branch` decides which
    # file holds it.
    path = _session_path(project_root, session_id if as_branch else "")
    try:
        # Preserve an id the file already carries. Re-reading it here rather than trusting the caller means an
        # ordinary turn -- which passes no id -- does not erase the identity a fork recorded, and a session does
        # not silently become a different session halfway through.
        existing_id = ""
        if not session_id:
            try:
                existing_id = str((load_session(project_root) or {}).get("session_id") or "")
            except Exception:  # noqa: BLE001
                existing_id = ""
        # The fence is *detected* whenever this caller holds a claim; `strict` only decides whether a detected
        # conflict refuses the write or is reported alongside it. The first version gated the whole check on
        # `strict`, so a non-strict caller was not fenced at all -- the detection silently did not run, which
        # made `strict=False` mean "no fence" rather than "soft fence". Caught by a test asserting that a
        # displaced writer is refused in both modes.
        fenced = False
        reason = ""
        if writer_id:
            holder = str((load_session(project_root) or {}).get(SESSION_CLAIM_FIELD) or "")
            if holder and holder != writer_id:
                fenced = True
                reason = (
                    "another writer claimed this session after it was loaded "
                    f"(holder {holder!r}, this writer {writer_id!r})"
                )
                if strict:
                    return SaveOutcome(
                        written=False,
                        fenced=True,
                        reason=reason + "; the write was refused so the newer transcript is not destroyed",
                    )
                # Soft mode: the caller asked to write regardless, so the write proceeds and carries this
                # caller's claim -- but the conflict is still reported, because a caller that never learns it
                # was displaced has the same bug as one that was silently overwritten.
                reason += "; written anyway because strict=False"

        data = {
            "saved_at": time.time(),
            "provider": provider,
            "model": model,
            "mode": mode,
            "effort": effort,
            "thinking": thinking,
            "messages": serialize_messages(messages),
        }
        # The session's own identity, so a branch can name its parent durably.
        #
        # Absent before session lineage existed, which made a fork unable to record what it came from: the only
        # stable thing to reference was the file path, and every branch overwrites the same file. Recorded only
        # when the caller supplies one, so an existing caller is unaffected, and `load_session` returning a file
        # with no id is handled by the lineage layer rather than assumed away here.
        if session_id:
            data["session_id"] = session_id
        elif existing_id:
            data["session_id"] = existing_id
        if writer_id:
            data[SESSION_CLAIM_FIELD] = writer_id
        # Highest-frequency write of the three files this session's atomic-write pass touched
        # (every single run_turn call saves) -- and therefore the one most likely to actually
        # get hit by a crash/Ctrl-C mid-write in practice, corrupting session.json.
        atomic_write_text(path, json.dumps(data, indent=2))
        return SaveOutcome(written=True, fenced=fenced, reason=reason)
    except Exception as exc:  # noqa: BLE001
        # Best-effort -- never let a save failure break a turn.
        return SaveOutcome(written=False, reason=f"{type(exc).__name__}: {exc}")


def claim_session(project_root: Path | None = None, writer_id: str = "") -> tuple[str, bool]:
    """Take or renew the writer claim on a session. Returns `(claim, took_over)`.

    Called once when a process starts a session. If the file already carries a different claim, this caller
    becomes the new holder and `took_over` is True -- the other process is not killed, it will simply be fenced
    at its next save, which is the correct outcome when two processes genuinely both want the session.

    **The claim is persisted here, and that is load-bearing.** The first version only returned the id, so the
    new holder was immediately fenced by the *old* holder's claim still sitting on disk -- `save_session` would
    compare B's id against A's stored claim, mismatch, and refuse B's very first write. A claim that is not
    written down is not a claim. Found by a test where the second writer could not save at all.

    The write preserves everything already in the file and only updates the claim field, so claiming never
    destroys a transcript. It is unconditional rather than fenced on purpose: taking over is the whole point of
    calling this, and the displaced writer is the one that should be refused, not the new one.
    """
    writer_id = writer_id or new_writer_id()
    path = _session_path(project_root)
    try:
        current = load_session(project_root) or {}
        previous = str(current.get(SESSION_CLAIM_FIELD) or "")
        current[SESSION_CLAIM_FIELD] = writer_id
        current.setdefault("saved_at", time.time())
        path.parent.mkdir(parents=True, exist_ok=True)
        atomic_write_text(path, json.dumps(current, indent=2))
        return writer_id, bool(previous and previous != writer_id)
    except Exception:
        # If the claim cannot be written, return the id anyway: the caller's saves will go through the
        # unfenced path rather than failing, which is the pre-existing behaviour and better than a session
        # that cannot be persisted at all.
        return writer_id, False


def load_session(project_root: Path | None = None, session_id: str = "") -> dict | None:
    """Read a session. With no `session_id`, the main session file.

    Resolution order for a named session, and the order is the design:

    1. the **branch file** `branches/<id>.json`, because an inactive fork lives there;
    2. the **main file**, if it carries that id -- a branch is made active by being written to the main file, so the
       live copy of a session is the main one.

    Trying the branch first matters for the case where the same id exists in both: the main file is the one being
    appended to, while the branch file is the point the fork was taken from. Callers that want the live transcript
    read with no id.
    """
    if session_id:
        branch_path = _session_path(project_root, session_id)
        if branch_path.exists():
            try:
                return json.loads(branch_path.read_text(encoding="utf-8"))
            except (json.JSONDecodeError, OSError):
                pass
        main = _read_main(project_root)
        if main is not None and str(main.get("session_id") or "") == session_id:
            return main
        return None
    return _read_main(project_root)


def _read_main(project_root: Path | None = None) -> dict | None:
    path = _session_path(project_root)
    if not path.exists():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return None


def _serialize_content(content):
    if content is None or isinstance(content, str):
        return content
    if isinstance(content, list):
        return [item.model_dump() if hasattr(item, "model_dump") else item for item in content]
    return content


def serialize_messages(messages: list[dict]) -> list[dict]:
    serialized = []
    for m in messages:
        if "role" not in m:
            # Gemini's "type"-keyed shape (user_input/model_output/function_call/function_result)
            # has no "role" field and is already plain JSON-serializable dicts -- pass through
            # unchanged rather than force it through the Anthropic/OpenAI "role" shape below.
            serialized.append(m)
            continue
        entry = {"role": m["role"], "content": _serialize_content(m.get("content"))}
        if "tool_calls" in m:
            entry["tool_calls"] = m["tool_calls"]
        if "tool_call_id" in m:
            entry["tool_call_id"] = m["tool_call_id"]
        if "reasoning_details" in m:
            entry["reasoning_details"] = m["reasoning_details"]
        serialized.append(entry)
    return serialized
