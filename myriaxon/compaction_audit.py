"""Make compaction auditable — the one gap on UNU's harness risk list that Myriaxon failed.

`compaction.py` discards information in three ways and recorded none of them:

1. **Pruning.** Oversized tool results older than N turns are replaced by
   `"[pruned: tool result from N turn(s) ago, X chars removed ...]"`. The original is gone: the
   placeholder records the *size*, never the content, and nothing anywhere says which tool produced it.
2. **Transcript rendering.** `render_transcript` maps a message list to text for the summariser, keeping
   only the first 400 characters of each assistant block and writing
   `"tool result: [output omitted from summary]"` for every tool output. The summariser therefore never
   sees most of what it is summarising.
3. **The summary itself.** It is generated by the provider, replaces the entire old history, and no copy
   of the input or the output was kept.

The consequences are not theoretical:

* **An audit cannot explain a decision.** If the agent acted on something compaction removed, there is no way
  to establish what it saw. UNU's framework names this directly as a runtime risk.
* **Compaction cannot be improved.** Whether it loses something critical is unknowable without the
  before/after pair, so the only available strategy is to guess and hope.

## What this module records

Every removal and every summary, appended to a per-session JSONL log, with the removed content itself kept in a
content-addressed store beside it. Content addressing means identical spans are stored once, and it makes the
digest in the log a *verifiable* claim: `retrieve()` returns the bytes and the caller can re-hash them.

Design decisions worth stating:

* **Recording never raises into the caller.** Compaction happening mid-turn must not fail because the audit
  could not write. A failure is swallowed and counted; `Recorder.failures` exposes it so a test can assert it
  stayed zero rather than the failure being invisible.
* **The log is append-only JSONL**, one object per line, so a partially-written file is still readable up to
  the last complete line and can be read with a streaming parser.
* **Off by default for the hot path.** Pruning happens on every turn once history is old enough, so the
  recorder is opt-in per session and a no-op when disabled — an audit facility that costs on every turn gets
  turned off.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import threading
import time
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any

from .constants import CONFIG_DIR

# Where the logs and the content store live. Session-scoped by name, not by directory, so one sweep can find
# every session's audit without walking a tree.
AUDIT_DIR = CONFIG_DIR / "compaction-audit"
AUDIT_LOG_NAME = "compaction.jsonl"
CONTENT_DIR_NAME = "content"

# A single span larger than this is truncated in the *log* (its digest still refers to the full stored copy).
# The store keeps everything; only the inline preview is bounded, so the log stays greppable.
_MAX_INLINE_PREVIEW = 2_000


def _digest(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


@dataclass
class AuditEntry:
    """One thing compaction removed, or one summary it produced.

    `kind` is one of:
      * `prune`      — a tool result replaced by a placeholder
      * `summary`    — the result of summarising old history
      * `transcript` — the text handed to the summariser (recorded so the summary can be judged)
    """

    kind: str
    reason: str
    chars: int
    digest: str
    at: float
    session: str = ""
    turn: int | None = None
    age_turns: int | None = None
    tool: str = ""
    path: str = ""
    preview: str = ""
    extra: dict[str, Any] = field(default_factory=dict)

    def to_json(self) -> str:
        return json.dumps(asdict(self), ensure_ascii=False, sort_keys=True)


class Recorder:
    """Records compaction events to a per-session JSONL log plus a content-addressed store.

    Construct with `enabled=False` for a no-op instance: every method checks the flag first, so callers never
    branch on whether auditing is on.
    """

    def __init__(self, session: str = "default", enabled: bool = True, root: Path | None = None) -> None:
        self.session = session
        self.enabled = enabled
        self.root = (root or AUDIT_DIR) / session
        self.log_path = self.root / AUDIT_LOG_NAME
        self.content_dir = self.root / CONTENT_DIR_NAME
        self.entries = 0
        self.failures = 0
        self._lock = threading.Lock()

    # ---------------------------------------------------------------- recording

    def record_prune(
        self,
        original: str,
        *,
        tool: str = "",
        path: str = "",
        turn: int | None = None,
        age_turns: int | None = None,
        reason: str = "stale tool result",
    ) -> None:
        """Record a tool result that is about to be replaced by a prune placeholder."""
        self._record(
            kind="prune",
            reason=reason,
            content=original,
            tool=tool,
            path=path,
            turn=turn,
            age_turns=age_turns,
        )

    def record_summary(self, summary: str, *, reason: str = "rolling-window compaction") -> None:
        """Record a summary that replaced old history."""
        self._record(kind="summary", reason=reason, content=summary)

    def record_transcript(self, transcript: str, *, reason: str = "summariser input") -> None:
        """Record the exact text handed to the summariser.

        Without this the summary cannot be judged: a summary that dropped something is only distinguishable
        from a summary whose *input* never contained it by having both.
        """
        self._record(kind="transcript", reason=reason, content=transcript)

    def record_omission(self, content: str, *, omission: str, description: str) -> None:
        """Record a span the transcript renderer left out entirely.

        Distinct from `record_transcript`: that records what the summariser *received*, this records what it
        was denied. `render_transcript` deliberately drops tool payloads and attachments, and the docstring
        justifies it as a judgement call -- this is what makes that judgement reviewable.
        """
        self._record(
            kind="omission",
            reason=f"omitted from summariser input: {description}",
            content=content,
            extra={"omission": omission, "description": description},
        )

    def _record(
        self,
        *,
        kind: str,
        reason: str,
        content: str,
        tool: str = "",
        path: str = "",
        turn: int | None = None,
        age_turns: int | None = None,
        extra: dict[str, Any] | None = None,
    ) -> None:
        if not self.enabled:
            return
        try:
            digest = _digest(content)
            self._store(digest, content)
            entry = AuditEntry(
                kind=kind,
                reason=reason,
                chars=len(content),
                digest=digest,
                at=time.time(),
                session=self.session,
                turn=turn,
                age_turns=age_turns,
                tool=tool,
                path=path,
                preview=content[:_MAX_INLINE_PREVIEW],
                extra=extra or {},
            )
            with self._lock:
                self.root.mkdir(parents=True, exist_ok=True)
                with self.log_path.open("a", encoding="utf-8", newline="\n") as handle:
                    handle.write(entry.to_json() + "\n")
                self.entries += 1
        except Exception:
            # Compaction runs mid-turn. Failing it because the audit could not write would trade a silent
            # logging gap for a broken session, which is the wrong way round. Counted instead of swallowed.
            self.failures += 1

    def _store(self, digest: str, content: str) -> None:
        """Content-addressed store: the same span twice costs one file, and the digest verifies retrieval."""
        target = self.content_dir / digest[:2] / digest
        if target.exists():
            return
        target.parent.mkdir(parents=True, exist_ok=True)
        tmp = target.with_suffix(".tmp")
        tmp.write_text(content, encoding="utf-8", newline="")
        os.replace(tmp, target)

    # ---------------------------------------------------------------- reading

    def retrieve(self, digest: str) -> str | None:
        """The exact content a digest refers to, or None if it was never stored.

        Returns the bytes so a caller can re-hash and confirm — the digest is a claim, and this is how it is
        checked rather than trusted.
        """
        target = self.content_dir / digest[:2] / digest
        try:
            return target.read_text(encoding="utf-8")
        except OSError:
            return None

    def read_log(self) -> list[dict]:
        """Every recorded entry, oldest first. Tolerates a truncated final line."""
        if not self.log_path.is_file():
            return []
        entries: list[dict] = []
        for line in self.log_path.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if not line:
                continue
            try:
                entries.append(json.loads(line))
            except json.JSONDecodeError:
                # A partial final write. Skipping it is correct; the alternative is refusing to read the log.
                continue
        return entries

    def summary(self) -> dict:
        """Totals by kind, for a status line or a verify report."""
        totals: dict[str, int] = {}
        chars: dict[str, int] = {}
        for entry in self.read_log():
            kind = str(entry.get("kind", "?"))
            totals[kind] = totals.get(kind, 0) + 1
            chars[kind] = chars.get(kind, 0) + int(entry.get("chars", 0))
        return {"session": self.session, "entries": totals, "chars": chars,
                "recorded": self.entries, "failures": self.failures}

    # ---------------------------------------------------------------- compaction lock

    def record_compaction_start(self, *, messages: int = 0, kept_turns: int = 0) -> None:
        """Mark that a compaction has begun.

        ## Why the record IS the lock

        Compaction is the one operation that can destroy history, and it spans an await: the summariser call. A
        process that dies between "summarising" and "replacing" leaves the transcript in a state nobody can
        interpret from the transcript alone -- was the summary applied, or not?

        DeepSeek's harness writes a `compaction/start` record before the async yield and treats an unmatched start
        as evidence of an interrupted compaction on the next open (verified in
        `compaction-basic/src/region.ts`). Nothing extra is needed to detect the crash: **the absence of the
        matching end record is the signal**. A separate lock file would need its own staleness policy and could
        itself be left stale; an append-only record cannot.

        A failed close deliberately leaves the start detectable, which is the point.
        """
        self._record(
            kind="compaction-start",
            reason=f"compaction began ({messages} messages, keeping last {kept_turns} turns)",
            content=f"start:{messages}:{kept_turns}",
            extra={"messages": messages, "kept_turns": kept_turns},
        )

    def record_compaction_end(self, *, applied: bool, reason: str = "", summary_chars: int = 0) -> None:
        """Mark that a compaction finished, and whether its summary was applied.

        `applied=False` is a normal outcome, not a failure: the summary may have been refused for being no
        smaller than what it replaced. Recording that distinction is what stops a later reader concluding the
        compaction succeeded.
        """
        self._record(
            kind="compaction-end",
            reason=reason or ("applied" if applied else "not applied"),
            content=f"end:{applied}:{summary_chars}",
            extra={"applied": applied, "summary_chars": summary_chars},
        )

    def interrupted_compaction(self) -> dict | None:
        """An unfinished compaction in this session's log, or None.

        Scans backward and returns the first `compaction-start` that has no `compaction-end` after it. Backward
        rather than forward so the *most recent* interruption is the one reported, which is the one a caller
        about to compact needs to know about.
        """
        entries = self.read_log()
        for entry in reversed(entries):
            kind = str(entry.get("kind") or "")
            if kind == "compaction-end":
                # An end closes everything before it: whatever start preceded this was completed.
                return None
            if kind == "compaction-start":
                return entry
        return None


def interrupted_compactions(root: Path | None = None) -> list[dict]:
    """Every session whose log ends with an unfinished compaction. For `myriaxon doctor` and `audit`."""
    found: list[dict] = []
    for record in list_sessions(root):
        recorder = audit_for(record["session"], root)
        pending = recorder.interrupted_compaction()
        if pending is not None:
            found.append({"session": record["session"], "started_at": pending.get("at", 0),
                          "reason": pending.get("reason", "")})
    return found


# ---------------------------------------------------------------- module-level active recorder

_active: Recorder | None = None
_active_lock = threading.Lock()


def set_active(recorder: Recorder | None) -> None:
    """Install the recorder compaction should use, or None to disable. Called once per session."""
    global _active
    with _active_lock:
        _active = recorder


def active() -> Recorder | None:
    with _active_lock:
        return _active


def get_or_create(session: str = "default", enabled: bool = True) -> Recorder:
    """The active recorder, creating and installing one if none is set.

    Exists so call sites stay one line and cannot forget to install what they record into.
    """
    current = active()
    if current is not None:
        return current
    recorder = Recorder(session=session, enabled=enabled)
    set_active(recorder)
    return recorder


def audit_for(session: str, root: Path | None = None) -> Recorder:
    """A recorder bound to a named session, for reading an existing log without installing it."""
    return Recorder(session=session, enabled=False, root=root)


# ---------------------------------------------------------------- retrieval: shadowing, not deletion

# Handles are `sha256` hex, so this is the shape to accept and nothing else. Checked before touching the
# filesystem because a handle arrives from the model's context and is therefore untrusted input: a value like
# `../../etc/passwd` must not become a path. The digest is also the entire filename, so validation and path
# safety are the same check.
_HANDLE_RE = re.compile(r"^[0-9a-f]{64}$")


def _handle_of(entry: dict) -> str:
    return str(entry.get("digest") or "")


def recall(handle: str, session: str = "", root: Path | None = None) -> tuple[str | None, str]:
    """The exact content behind a handle. Returns `(content, problem)`.

    This is the other half of pruning, and the half that was missing. `record_prune` writes the full text to a
    content-addressed store and puts a placeholder in the transcript -- but a placeholder that only said
    *"re-run the tool"* made the model pay a whole tool call to recover something the harness already had on disk.

    The digest is verified rather than trusted: the content is re-hashed and compared to the handle it was found
    under. A store that has been corrupted, truncated or edited returns a problem instead of silently handing back
    the wrong text, because the model has no other way to tell.
    """
    candidate = (handle or "").strip()
    if not _HANDLE_RE.match(candidate):
        return None, (
            "That is not a valid handle. A handle is the 64-character hex digest shown in a pruned tool "
            "result, like `[pruned: ... call recall with handle 'a1b2...' to read the original]`."
        )

    # The named session first, then any other, because a handle can be quoted in a summary that outlives the
    # session it came from.
    searched: list[str] = []
    for name in ([session] if session else []) + [s["session"] for s in list_sessions(root)]:
        if not name or name in searched:
            continue
        searched.append(name)
        recorder = audit_for(name, root)
        content = recorder.retrieve(candidate)
        if content is None:
            continue
        actual = hashlib.sha256(content.encode("utf-8")).hexdigest()
        if actual != candidate:
            return None, (
                f"The stored content for {candidate[:12]}... does not match its handle. The store has been "
                "modified or corrupted, so the text is not being returned. Report this rather than trusting it."
            )
        return content, ""

    return None, (
        f"No stored content for handle {candidate[:12]}.... It may have been pruned before auditing was enabled, "
        "or the store may have been cleared. Re-run the original tool if you still need the result."
    )


def trace(handle: str, session: str = "", root: Path | None = None) -> list[dict]:
    """Every log entry that refers to a handle, newest first.

    Their `session_event_trace` equivalent: answering "where did this text come from?" turns a digest from an
    opaque token into something with a history. An entry refers to a handle when it *stores* it (its own digest)
    or when its `extra` cites it -- a summary citing the ranges it replaced, for instance.
    """
    wanted = (handle or "").strip()
    if not _HANDLE_RE.match(wanted):
        return []
    found: list[dict] = []
    for name in ([session] if session else []) + [s["session"] for s in list_sessions(root)]:
        if not name:
            continue
        for entry in audit_for(name, root).read_log():
            if _handle_of(entry) == wanted:
                found.append({**entry, "relation": "stored-here"})
                continue
            extra = entry.get("extra") or {}
            cited = extra.get("cites") or extra.get("shadowed") or []
            if isinstance(cited, list) and wanted in [str(c) for c in cited]:
                found.append({**entry, "relation": "cited-by"})
    found.sort(key=lambda e: float(e.get("at") or 0), reverse=True)
    return found


def search(query: str, session: str = "", root: Path | None = None, limit: int = 20) -> list[dict]:
    """Entries whose stored content contains `query`, newest first.

    Searches the *store*, not just the log, and that distinction is the point. The log keeps only a 2,000-character
    preview, so a search over the log alone cannot find something that was near the end of a 50,000-character tool
    result -- which is exactly the content worth recovering. Preview matches are reported separately so a caller
    can tell "found in the full text" from "found only in the preview we kept".
    """
    needle = (query or "").strip().lower()
    if not needle:
        return []
    limit = max(1, min(int(limit or 20), 100))
    hits: list[dict] = []
    for name in ([session] if session else []) + [s["session"] for s in list_sessions(root)]:
        if not name:
            continue
        recorder = audit_for(name, root)
        for entry in recorder.read_log():
            handle = _handle_of(entry)
            if not handle:
                continue
            where = ""
            content = recorder.retrieve(handle) if _HANDLE_RE.match(handle) else None
            if content is not None and needle in content.lower():
                where = "content"
            elif needle in str(entry.get("preview") or "").lower():
                where = "preview"
            if where:
                hits.append({
                    "handle": handle,
                    "session": name,
                    "kind": str(entry.get("kind") or ""),
                    "tool": str(entry.get("tool") or ""),
                    "chars": int(entry.get("chars") or 0),
                    "at": float(entry.get("at") or 0),
                    "matched_in": where,
                })
    hits.sort(key=lambda h: h["at"], reverse=True)
    return hits[:limit]


def render_recall(content: str, handle: str, max_chars: int = 40_000) -> str:
    """The text handed back to the model, bounded and labelled.

    Bounded because the whole reason this content left the transcript was that it was too large to keep. Handing
    it back unbounded would put the harness straight back where it started, one call later -- so the tail is cut
    with a note saying how to get the rest rather than silently truncated.
    """
    body = content
    note = (
        f"[recalled {handle[:12]}...: {len(content):,} chars, recorded when it was removed from the "
        "conversation. This is the original text.]"
    )
    if len(content) > max_chars:
        body = content[:max_chars]
        note += (
            f"\n[... truncated at {max_chars:,} chars. The full text is still in the store under this same "
            "handle; recall it again with a narrower question, or grep_search the compaction-audit directory.]"
        )
    return f"{note}\n\n{body}"


