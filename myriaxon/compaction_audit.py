def list_sessions(root: Path | None = None) -> list[dict]:
    """Every session that has an audit log, newest first.

    Exists for the `audit` command: a log nobody can enumerate is a log nobody reads.
    """
    base = root or AUDIT_DIR
    if not base.is_dir():
        return []
    found: list[dict] = []
    for entry in sorted(base.iterdir()):
        log = entry / AUDIT_LOG_NAME
        if not (entry.is_dir() and log.is_file()):
            continue
        entries = 0
        chars = 0
        try:
            for line in log.read_text(encoding="utf-8").splitlines():
                line = line.strip()
                if not line:
                    continue
                try:
                    record = json.loads(line)
                except json.JSONDecodeError:
                    continue
                entries += 1
                chars += int(record.get("chars", 0))
            modified = time.strftime("%Y-%m-%d %H:%M", time.localtime(log.stat().st_mtime))
        except OSError:
            continue
        found.append({"session": entry.name, "entries": entries, "chars": chars, "modified": modified})
    found.sort(key=lambda item: item["modified"], reverse=True)
    return found


def latest_session(root: Path | None = None) -> str:
    """The most recently written session name, or "" when there is none."""
    sessions = list_sessions(root)
    return sessions[0]["session"] if sessions else ""
